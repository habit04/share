const unicode = (text) => text.replace(/\\U\+([0-9a-f]{4})/gi, (_, hex) => String.fromCharCode(parseInt(hex, 16)));
const metadataTypes = new Set(['DICTIONARY', 'ACDBDICTIONARYWDFLT', 'FIELD', 'FIELDLIST', 'XRECORD']);
const canonicalHandle = (text) => BigInt('0x' + text.trim()).toString(16).toUpperCase();

function entityShape(entity) {
  if (entity.type === 'line') return { type: 'line', a: entity.a, b: entity.b };
  assert.equal(entity.type, 'mtext', 'Independent metadata fixtures contain only LINE and MTEXT geometry');
  const live = entity.field && entity.field.value === entity.text;
  return { type: 'mtext', position: entity.position, height: entity.height, width: entity.width,
    rotation: entity.rotation, ...(live ? { fieldCode: entity.field.code, nativeField: entity.field.native === true } : { text: entity.text }) };
}

/** Compare logical metadata, including reference kind/order, across fresh file identities.
 * Entity geometry is generated by the codec; its retained source groups are not the edited geometry. */
function metadataSignature(state) {
  const graph = state.graph;
  assert.equal(graph?.schema, 1, 'A complete retained graph is mandatory');
  const nodes = new Map(graph.nodes.map(node => [node.id, node]));
  const entities = new Map(state.entities.map(entity => [entity.id, entity]));
  const otherEntities = new Map();
  for (const [name, block] of Object.entries(state.blocks ?? {})) block.entities.forEach((entity, index) => {
    assert.ok(!entities.has(entity.id) && !otherEntities.has(entity.id), 'Block entity identities are unique');
    otherEntities.set(entity.id, { entity, label: 'block:' + JSON.stringify(name) + '/entity:' + index });
  });
  for (const layout of state.layouts ?? []) layout.entities.forEach((entity, index) => {
    assert.ok(!entities.has(entity.id) && !otherEntities.has(entity.id), 'Layout entity identities are unique');
    otherEntities.set(entity.id, { entity, label: 'layout:' + JSON.stringify(layout.name) + '/entity:' + index });
  });
  const labels = new Map(), selected = new Set(), queue = [];
  const assign = (node, label, retain = false) => {
    if (!labels.has(node.id)) { labels.set(node.id, label); queue.push(node); }
    if (retain) selected.add(node.id);
  };
  for (const node of graph.nodes) {
    const anchor = node.anchor;
    if (anchor?.kind === 'entity' && !anchor.part) {
      const modelEntity = entities.get(anchor.id), other = otherEntities.get(anchor.id);
      const entity = modelEntity ?? other?.entity; assert.ok(entity, 'Retained entity anchor resolves to live geometry');
      const geometry = entity.type === 'line' ? [entity.a, entity.b] : entity.position;
      // These independent fixtures compare model metadata. Generated default blocks
      // still require live anchors; their full records are checked by native postflight.
      assign(node, modelEntity ? 'entity:' + entity.type + ':' + JSON.stringify(geometry) : other.label, !!modelEntity);
      if (modelEntity || entity.cadIdentity) assert.equal(entity.cadIdentity, node.id, 'Metadata-bearing fixture entities carry their own unique identities');
    } else if (anchor?.kind === 'table') assign(node, `table:${anchor.table}:${anchor.name}`);
    else if (anchor?.kind === 'dictionary') assign(node, 'dictionary:' + JSON.stringify(anchor.path), anchor.path[0]?.startsWith('JCAD_METADATA_ORACLE'));
    if (node.type === 'FIELDLIST') { assign(node, 'field-list', true); }
  }
  for (let cursor = 0; cursor < queue.length; cursor++) {
    const node = queue[cursor], label = labels.get(node.id); let child = 0;
    for (const ref of node.references ?? []) {
      const code = node.groups[ref.groupIndex]?.[0];
      if (!ref.target || ref.role === 'owner' || !(ref.role === 'extension' || ref.kind === 'hard-owner' || ref.kind === 'soft-owner')) continue;
      const target = nodes.get(ref.target); assert.ok(target, 'Owned metadata references have live targets');
      const key = node.groups[ref.groupIndex - 1];
      const suffix = ref.role === 'extension' ? '/extension' : key?.[0] === 3 ? '/key:' + JSON.stringify(key[1]) : node.type === 'FIELD' && code === 360 ? '/child:' + child++ : '/owned:' + ref.groupIndex;
      assign(target, label + suffix, selected.has(node.id));
    }
  }
  const generated = new Map((graph.generatedHandles ?? []).map(hint => [canonicalHandle(hint.handle), 'generated:' + hint.key]));
  const targetLabel = (ref) => {
    if (ref.target) {
      const node = nodes.get(ref.target); assert.ok(node, 'Declared metadata target exists');
      return labels.get(node.id) ?? `unrooted:${node.type}:${node.sourceHandle ?? node.id}`;
    }
    const handle = canonicalHandle(ref.sourceHandle ?? '0');
    return handle === '0' ? null : generated.get(handle) ?? 'external:' + handle;
  };
  const normalize = (code, raw, opaque) => {
    if (code >= 160 && code <= 169) { assert.match(raw.trim(), /^-?\d+$/); return BigInt(raw.trim()).toString(); }
    if (code >= 310 && code <= 319 || code === 1004) return raw.trim().toUpperCase();
    if (code >= 10 && code <= 99 || code >= 110 && code <= 149 || code >= 170 && code <= 179 || code >= 210 && code <= 299 || code >= 370 && code <= 389 || code >= 400 && code <= 469 || code >= 1010 && code <= 1059 || code === 1070 || code === 1071) {
      const number = Number(raw); assert.ok(Number.isFinite(number), 'Metadata numeric values are finite'); return number;
    }
    return opaque ? raw : unicode(raw);
  };
  const records = [];
  for (const id of selected) {
    const node = nodes.get(id), references = new Map((node.references ?? []).map(ref => [ref.groupIndex, ref]));
    const entity = node.anchor?.kind === 'entity';
    if (!entity && !metadataTypes.has(node.type)) continue;
    const keep = new Set(); let brace = 0, app = false;
    if (entity) node.groups.forEach(([code, raw], index) => {
      if (code === 102) { keep.add(index); brace += raw.startsWith('{') ? 1 : raw === '}' ? -1 : 0; }
      else if (brace || code === 1001 || app) { keep.add(index); if (code === 1001) app = true; }
    });
    const combined = node.type === 'FIELD' ? [[2, 3], [301, 9]] : [];
    const seen = new Set(), groups = [];
    node.groups.forEach(([code, raw], index) => {
      if (code === 5 || code === 105 || entity && !keep.has(index)) return;
      const chunks = combined.find(codes => codes.includes(code));
      if (chunks) {
        if (!seen.has(chunks[0])) groups.push([chunks[0], unicode(node.groups.filter(([code]) => chunks.includes(code)).map(([, value]) => value).join(''))]);
        seen.add(chunks[0]); return;
      }
      const ref = references.get(index);
      groups.push([code, ref ? { kind: ref.kind, role: ref.role ?? null, target: targetLabel(ref) } : normalize(code, raw, node.type === 'XRECORD' || code === 1000)]);
    });
    records.push({ identity: labels.get(id), type: node.type, groups });
  }
  records.sort((a, b) => a.identity.localeCompare(b.identity));
  return { entities: state.entities.map(entityShape).sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b))),
    views: state.views.slice().sort((a, b) => a.name.localeCompare(b.name)), records, annotationSettings: state.annotationSettings };
}

function same(actual, expected, label) {
  if (typeof expected === 'number') {
    assert.ok(Number.isFinite(actual) && Math.abs(actual - expected) <= 1e-8 * Math.max(1, Math.abs(expected)), label); return;
  }
  if (Array.isArray(expected)) { assert.ok(Array.isArray(actual), label); assert.equal(actual.length, expected.length, label); expected.forEach((value, index) => same(actual[index], value, `${label}[${index}]`)); return; }
  if (expected && typeof expected === 'object') { assert.deepEqual(Object.keys(actual ?? {}).sort(), Object.keys(expected).sort(), label); for (const key of Object.keys(expected)) same(actual[key], expected[key], `${label}.${key}`); return; }
  assert.deepEqual(actual, expected, label);
}

/** @typedef {{ kind: 'imported-dwg' | 'authored-clipboard', sessionId: number, contentGeneration: number, documentId: string | null, pages: string, importReport: string | null, nativeLayoutCount: number }} MetadataSaveOrigin */

/** Capture actual page provenance before Save As; graph.sourceFormat alone can come from clipboard entities.
 * This callback is serialized by Playwright and therefore has no module dependencies.
 * @param {'imported-dwg' | 'authored-clipboard'} kind
 * @returns {MetadataSaveOrigin}
 */
export function captureMetadataSaveOrigin(kind) {
  const ed = window.editor, session = ed.sessions.current, state = ed.doc.snapshot;
  const report = state.meta?.importReport, nativeLayoutCount = state.cadGraph?.nodes.filter(node => node.type === 'LAYOUT').length ?? 0;
  const imported = kind === 'imported-dwg' && report?.format === 'DWG' && nativeLayoutCount > 0;
  const authored = kind === 'authored-clipboard' && report === undefined && nativeLayoutCount === 0;
  if (!imported && !authored) throw new Error('Unexpected metadata Save origin: ' + JSON.stringify({ kind, reportFormat: report?.format ?? null, sourcePath: report?.sourcePath ?? null, nativeLayoutCount, graphSourceFormat: state.cadGraph?.sourceFormat ?? null }));
  return { kind, sessionId: session.id, contentGeneration: session.contentGeneration, documentId: state.cadGraph?.documentId ?? null,
    pages: JSON.stringify(state.layouts ?? null), importReport: report === undefined ? null : JSON.stringify(report), nativeLayoutCount };
}

/** Validate the captured origin and derive actual source-loss consent before starting Save.
 * This callback is serialized by Playwright and therefore has no module dependencies.
 * @param {{ path: string, origin: MetadataSaveOrigin }} input
 */
export function metadataSavePreflight({ path, origin }) {
  const ed = window.editor, session = ed.sessions.current, state = ed.doc.snapshot;
  const report = state.meta?.importReport, nativeLayoutCount = state.cadGraph?.nodes.filter(node => node.type === 'LAYOUT').length ?? 0;
  const imported = origin.kind === 'imported-dwg' && report?.format === 'DWG' && nativeLayoutCount > 0;
  const authored = origin.kind === 'authored-clipboard' && report === undefined && nativeLayoutCount === 0;
  const current = { sessionId: session.id, contentGeneration: session.contentGeneration, documentId: state.cadGraph?.documentId ?? null,
    pages: JSON.stringify(state.layouts ?? null), importReport: report === undefined ? null : JSON.stringify(report), nativeLayoutCount };
  if (ed.doc.filePath !== path || !imported && !authored
    || current.sessionId !== origin.sessionId || current.contentGeneration !== origin.contentGeneration
    || current.documentId !== origin.documentId || current.pages !== origin.pages
    || current.importReport !== origin.importReport || current.nativeLayoutCount !== origin.nativeLayoutCount) {
    throw new Error('In-place metadata Save origin changed: ' + JSON.stringify({ kind: origin.kind, path, currentPath: ed.doc.filePath, reportFormat: report?.format ?? null, sourcePath: report?.sourcePath ?? null, nativeLayoutCount, sessionId: session.id, contentGeneration: session.contentGeneration }));
  }
  if (imported) {
    const counts = Object.values(report.counts ?? {});
    if (report.recovered || report.omitted !== 0
      || !counts.every(count => Object.values(count).every(value => Number.isInteger(value) && value >= 0))
      || counts.reduce((sum, count) => sum + (count.dropped ?? 0) + (count.simplified ?? 0), 0) !== 0
      || report.counts.LAYOUT?.kept !== state.layouts?.length || !report.counts.LAYOUT?.kept
      || (report.counts.LAYOUT?.unsupported ?? 0) !== 0) {
      throw new Error('In-place metadata Save has an unexpected import report or lost native page settings: ' + JSON.stringify({ kind: origin.kind, sourcePath: report.sourcePath, counts: report.counts, layouts: state.layouts?.length ?? 0 }));
    }
  }
  const w = /** @type {any} */ (window);
  w.__metadataSaving = { snapshot: state, session: session.id, path };
  // Fixed paths are distinct regular files. A Save As state can still carry an
  // original-source report; authored clipboard data is not an imported document.
  return imported && report.sourcePath === path && Object.values(report.counts).reduce((sum, count) => sum + (count.unsupported ?? 0), 0) > 0;
}

