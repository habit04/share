// Autosave / Drawing Recovery files in the app data folder (main process side).
//
//   autosave/<document id>.sv.dxf   the DXF text of one open drawing (id = a UUID the renderer gives
//                                   every document once; it never repeats across launches)
//   autosave/<name>_<tag>_jcadproj.sv.dxf
//                                   the unsaved changes of the open project (src/app/project-autosave.ts)
//   autosave/index.json             { version: 1, entries: { "<id>.sv.dxf": { title, originalPath, savedAt } } }
//
// Every file is written through atomic-write.cjs (temporary file + fsync + rename), and the index is
// rewritten one write at a time. Files from 0.4.0 and earlier were named after the drawing title
// plus a session number that restarted at every launch (Drawing1_1.sv.dxf + Drawing1_1.sv.dxf.json),
// so a new launch could overwrite an unrecovered backup; they are renamed to fresh ids and moved into
// the index the first time the folder is used.
'use strict';

const path = require('node:path');
const crypto = require('node:crypto');
const fsp = require('node:fs/promises');
const { createAtomicWriter, createWriteQueue, isTempName } = require('./atomic-write.cjs');

const ID_NAME_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.sv\.dxf$/i;
const NAME_RE = /^[A-Za-z0-9_-]{1,60}\.sv\.dxf$/;
/**
 * The old scheme: "<title>_<session number>.sv.dxf". Only these are migrated; other names in the
 * folder are kept as they are - in particular the project's own autosave
 * ("<name>_<hash>_jcadproj.sv.dxf", src/app/project-autosave.ts), which the project recovery
 * finds by that suffix and which would otherwise turn into a "drawing" nobody can open.
 */
const LEGACY_NAME_RE = /^[A-Za-z0-9_-]{0,58}_\d+\.sv\.dxf$/;
/** The project autosave (twin of SUFFIX in src/app/project-autosave.ts): keeps its name across launches. */
const PROJECT_SUFFIX = '_jcadproj.sv.dxf';
/**
 * The project's own autosave (src/app/project-autosave.ts: "<name>_<path hash>_jcadproj.sv.dxf").
 * It is a current-scheme name, not an old drawing backup: renaming it to an id would hide it from
 * Project Recovery and list its JSON in the Drawing Recovery Manager as if it were a drawing.
 */
const PROJECT_NAME_RE = /_jcadproj\.sv\.dxf$/;

/** A drawing backup in the 0.4.0 naming scheme (renamed to a permanent id on first use). */
function isLegacyName(name) {
  return NAME_RE.test(name) && LEGACY_NAME_RE.test(name) && !ID_NAME_RE.test(name) && !name.endsWith(PROJECT_SUFFIX);
}
const INDEX = 'index.json';

/** Autosave names are generated by the renderer but restricted to a safe charset inside our folder. */
function safeAutosaveName(name) {
  if (typeof name !== 'string' || !NAME_RE.test(name)) throw new Error('Invalid autosave name');
  return name;
}

function cleanMeta(m, fallbackTitle) {
  const o = m && typeof m === 'object' ? m : {};
  const savedAt = Number(o.savedAt);
  return {
    originalPath: typeof o.originalPath === 'string' && o.originalPath.length <= 4096 ? o.originalPath : null,
    title: String(o.title || fallbackTitle).slice(0, 260),
    savedAt: Number.isFinite(savedAt) && savedAt > 0 ? Math.round(savedAt) : Date.now(),
  };
}

/** "Panel_A_3.sv.dxf" -> "Panel_A.dxf" (only used when an old file has no metadata sidecar). */
function legacyTitle(name) {
  return `${name.replace(/\.sv\.dxf$/, '').replace(/_\d+$/, '') || 'Drawing'}.dxf`;
}

/** Title of a backup the index does not know (a truncated or deleted index.json). */
function fallbackTitle(name) {
  if (ID_NAME_RE.test(name)) return 'Recovered drawing.dxf';
  if (name.endsWith(PROJECT_SUFFIX)) return 'Recovered project';
  return legacyTitle(name);
}

function createAutosaveStore(dir, deps = {}) {
  const fs = deps.fs || fsp;
  const writer = deps.writer || createAtomicWriter(fs);
  const newId = deps.uuid || (() => crypto.randomUUID());
  const enqueue = createWriteQueue();
  const indexFile = path.join(dir, INDEX);
  /** name -> metadata; null until the folder was read once this launch. */
  let entries = null;
  let ready = null;
  /** Names migrated from the old scheme in this launch (old name -> new name), for the log / tests. */
  const migrated = [];

  async function readIndex() {
    let text;
    try {
      text = await fs.readFile(indexFile, 'utf8');
    } catch (err) {
      if (err && err.code === 'ENOENT') return {};
      throw err;
    }
    try {
      const parsed = JSON.parse(text);
      return parsed && parsed.entries && typeof parsed.entries === 'object' ? { ...parsed.entries } : {};
    } catch {
      return {}; // unreadable JSON: rebuilt from the files below (titles fall back to the file names)
    }
  }

  function saveIndex() {
    return enqueue(indexFile, async () => {
      await fs.mkdir(dir, { recursive: true });
      await writer.atomicWriteFile(indexFile, JSON.stringify({ version: 1, entries }, null, 1));
    });
  }

  async function init() {
    const loaded = await readIndex();
    let files;
    try {
      files = await fs.readdir(dir);
    } catch (err) {
      if (err && err.code === 'ENOENT') {
        entries = loaded;
        return;
      }
      throw err;
    }
    entries = loaded;
    let changed = false;
    for (const f of files) {
      // Our own temporary files are only left behind by a crash mid-write.
      if (isTempName(f)) await fs.rm(path.join(dir, f), { force: true }).catch(() => {});
    }
    for (const f of files) {
      // Only old-style drawing backups; the project autosave is found by its name at every start.
      if (!isLegacyName(f)) continue;
      let meta = null;
      try {
        meta = JSON.parse(await fs.readFile(path.join(dir, `${f}.json`), 'utf8'));
      } catch {
        /* no sidecar */
      }
      if (!meta || !Number(meta.savedAt)) {
        try {
          meta = { ...(meta || {}), savedAt: (await fs.stat(path.join(dir, f))).mtimeMs };
        } catch {
          /* keep what we have */
        }
      }
      const clean = cleanMeta(meta, legacyTitle(f));
      const next = `${newId()}.sv.dxf`;
      try {
        await fs.rename(path.join(dir, f), path.join(dir, next));
        entries[next] = clean;
        migrated.push([f, next]);
        await fs.rm(path.join(dir, `${f}.json`), { force: true }).catch(() => {});
      } catch {
        entries[f] = clean; // could not rename: keep it listed under its old name
      }
      changed = true;
    }
    const present = new Set(files.filter((f) => f.endsWith('.sv.dxf')).map((f) => migrated.find(([a]) => a === f)?.[1] ?? f));
    for (const name of Object.keys(entries)) {
      if (!present.has(name)) {
        delete entries[name];
        changed = true;
      }
    }
    // Files the index does not know (a truncated or deleted index.json): list them from the folder
    // with the file time, so the index is complete again after start-up.
    for (const name of present) {
      if (entries[name] || !NAME_RE.test(name)) continue;
      try {
        const savedAt = (await fs.stat(path.join(dir, name))).mtimeMs;
        entries[name] = cleanMeta({ savedAt }, fallbackTitle(name));
        changed = true;
      } catch {
        /* removed meanwhile */
      }
    }
    if (changed) await saveIndex();
  }

  /** Read the folder once per launch (migrating old files); a failure is retried on the next call. */
  function ensure() {
    if (!ready) {
      ready = init().catch((err) => {
        ready = null;
        throw err;
      });
    }
    return ready;
  }

  return {
    dir,
    migrated,
    ensure,
    async write(name, text, meta) {
      const n = safeAutosaveName(name);
      if (typeof text !== 'string') throw new Error('Invalid payload');
      await ensure();
      const file = path.join(dir, n);
      // Everything about one backup (its file and its index entry) changes inside its own queue, so a
      // write and a remove of the same name take effect in the order they were called.
      await enqueue(file, async () => {
        await fs.mkdir(dir, { recursive: true });
        await writer.atomicWriteFile(file, text);
        entries[n] = cleanMeta(meta, n);
      });
      await saveIndex();
    },
    /** Every backup, newest first. Throws (instead of answering "nothing") when the folder cannot be read. */
    async list() {
      await ensure();
      let files;
      try {
        files = await fs.readdir(dir);
      } catch (err) {
        if (err && err.code === 'ENOENT') return [];
        throw err;
      }
      const out = [];
      for (const f of files) {
        if (!f.endsWith('.sv.dxf') || !NAME_RE.test(f)) continue;
        let meta = entries[f];
        if (!meta) {
          let savedAt = 0;
          try {
            savedAt = (await fs.stat(path.join(dir, f))).mtimeMs;
          } catch {
            continue; // removed meanwhile
          }
          meta = cleanMeta({ savedAt }, fallbackTitle(f));
        }
        out.push({ name: f, ...meta });
      }
      return out.sort((a, b) => b.savedAt - a.savedAt);
    },
    /** The DXF text, null when the backup no longer exists; other failures are thrown. */
    async read(name) {
      const n = safeAutosaveName(name);
      try {
        return await fs.readFile(path.join(dir, n), 'utf8');
      } catch (err) {
        if (err && err.code === 'ENOENT') return null;
        throw err;
      }
    },
    async remove(name) {
      const n = safeAutosaveName(name);
      await ensure();
      const file = path.join(dir, n);
      const listed = await enqueue(file, async () => {
        await fs.rm(file, { force: true });
        await fs.rm(`${file}.json`, { force: true });
        const had = !!entries && n in entries;
        if (had) delete entries[n];
        return had;
      });
      if (listed) await saveIndex();
    },
  };
}

module.exports = { createAutosaveStore, safeAutosaveName, isLegacyName, ID_NAME_RE, LEGACY_NAME_RE, PROJECT_NAME_RE, legacyTitle };
