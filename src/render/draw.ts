const bitmaps = new Map<string, ImageBitmap | null | 'pending'>();

/** The loaded bitmap for a path, starting the load on first use (null while pending or unavailable). */
export function imageBitmap(path: string, loader: ImageLoader | undefined = renderSettings.imageLoader): ImageBitmap | null {
  if (!loader || !path) return null;
  const hit = bitmaps.get(path);
  if (hit === 'pending') return null;
  if (hit !== undefined) return hit;
  bitmaps.set(path, 'pending');
  loader(path)
    .then((bmp) => {
      bitmaps.set(path, bmp);
      if (bmp) renderSettings.requestRedraw?.();
    })
    .catch(() => bitmaps.set(path, null));
  return null;
}

/** Forget cached bitmaps (after the loader changes or files were edited). */
export function clearImageCache(): void {
  bitmaps.clear();
}

export function resolveLineWidth(e: Entity, layers: readonly Layer[], _tf: Transform): number {
  if (!lineweightDisplay.enabled) return 1;
  const layer = layers.find((l) => l.name === e.layer);
  const mm = e.lineWeight !== undefined && e.lineWeight >= 0 ? e.lineWeight : (layer?.lineWeight ?? 0.25);
  if (lineweightDisplay.pxPerMm) return Math.max(1, mm * lineweightDisplay.pxPerMm);
  return Math.max(1, Math.round((mm / 0.25) * 10) / 10);
}

/** Canvas dash array for an entity at the current zoom ([] = continuous). */
export function resolveDash(e: Entity, layers: readonly Layer[], tf: Transform): number[] {
  const layer = layers.find((l) => l.name === e.layer);
  const name = effectiveLinetype(e.linetype, layer?.linetype);
  const lt = findLinetype(name, renderSettings.linetypes);
  if (!lt || lt.pattern.length === 0) return [];
  return dashArray(lt.pattern, renderSettings.ltscale * (e.ltscale ?? 1), tf.scale);
}

/** Draw a single entity. Inserts are exploded recursively. */
export function drawEntity(
  ctx: CanvasRenderingContext2D,
  e: Entity,
  tf: Transform,
  layers: readonly Layer[],
  lookup: BlockLookup,
  style: DrawStyle = {},
): void {
  const rotation = tf.rotation;
  if (rotation && Number.isFinite(rotation)) {
    // Entity painters use an unrotated, Y-down screen. Rotate the whole painter so native
    // arcs, ellipses, font glyphs, images, hatch patterns and block attributes share one view.
    const c = Math.cos(rotation), s = Math.sin(rotation);
    const base: Transform = { ...tf, rotation: 0, toScreen: (point) => {
      const { x, y } = tf.toScreen(point);
      return { x: c * x - s * y, y: s * x + c * y };
    } };
    ctx.save();
    try {
      ctx.rotate(-rotation);
      drawEntity(ctx, e, base, layers, lookup, style);
    } finally { ctx.restore(); }
    return;
  }
  // Annotative objects (Track E hook, see annotationDisplay).
  if (e.annotative) {
    if (annotationDisplay.hide) return;
    if (annotationDisplay.factor !== 1) e = annotativeEntity(e, annotationDisplay.factor);
  }
  const plotted = plottedAppearance(e, layers, style);
  const color = style.strokeOverride ?? plotted?.color ?? resolveColor(e, layers);
  const width = style.lineWidthOverride ?? plotted?.width ?? resolveLineWidth(e, layers, tf);
  const baseAlpha = style.alpha ?? ctx.globalAlpha;
  canvasSave(ctx, () => {
    ctx.strokeStyle = color;
    ctx.fillStyle = color;
    ctx.lineWidth = width;
    ctx.lineCap = 'butt';
    ctx.lineJoin = 'miter';
    ctx.globalAlpha = baseAlpha * resolveAlpha(e, layers);
    if (style.dashed) ctx.setLineDash([6, 4]);
    else ctx.setLineDash(resolveDash(e, layers, tf));
    drawGeometry(ctx, e, tf, layers, lookup, { ...style, alpha: baseAlpha });
  });
}

/** Clip an infinite / semi-infinite line to the view (or a large span) and return its screen endpoints. */
function constructionLineEnds(e: XlineEntity | RayEntity, tf: Transform): [Point, Point] | null {
  const d = g.normalize(e.direction);
  const vb = tf.viewBounds;
  let tMin = e.type === 'ray' ? 0 : -1e6;
  let tMax = 1e6;
  if (vb) {
    // Liang–Barsky style parametric clip against the view rectangle (padded)
    const pad = Math.max(vb.max.x - vb.min.x, vb.max.y - vb.min.y);
    const box = { min: { x: vb.min.x - pad, y: vb.min.y - pad }, max: { x: vb.max.x + pad, y: vb.max.y + pad } };
    for (const [p0, dir, lo, hi] of [
      [e.base.x, d.x, box.min.x, box.max.x],
      [e.base.y, d.y, box.min.y, box.max.y],
    ] as Array<[number, number, number, number]>) {
      if (Math.abs(dir) < 1e-12) {
        if (p0 < lo || p0 > hi) return null;
        continue;
      }
      let t1 = (lo - p0) / dir;
      let t2 = (hi - p0) / dir;
      if (t1 > t2) [t1, t2] = [t2, t1];
      tMin = Math.max(tMin, t1);
      tMax = Math.min(tMax, t2);
    }
    if (tMin > tMax) return null;
  }
  return [g.add(e.base, g.scale(d, tMin)), g.add(e.base, g.scale(d, tMax))];
}

function strokePolyline(ctx: CanvasRenderingContext2D, e: PolylineEntity, tf: Transform): void {
  if (e.points.length === 0) return;
  ctx.beginPath();
  const p0 = tf.toScreen(e.points[0]!);
  ctx.moveTo(p0.x, p0.y);
  for (const s of polylineSegments(e)) {
    if (s.arc) {
      const c = tf.toScreen(s.arc.center);
      ctx.arc(c.x, c.y, s.arc.radius * tf.scale, -s.arc.startAngle, -s.arc.endAngle, true);
    } else {
      const p = tf.toScreen(s.b);
      ctx.lineTo(p.x, p.y);
    }
  }
  if (e.closed) ctx.closePath();
}

function drawText(ctx: CanvasRenderingContext2D, e: TextEntity, tf: Transform, geometry?: TextGeometryContext): void {
  const source = e;
  const appearance = geometry?.resolve(e);
  const nativeStroke = appearance?.kind === 'stroke' && appearance.shxResourceId && geometry?.shxRun?.(e.text, e.height, appearance)?.ok;
  const measured = geometry && (appearance?.kind === 'canvas' || nativeStroke) ? metricTextPlacement(e, geometry) : null;
  e = measured?.text ?? placedText(e, strokeTextWidth);
  const p = tf.toScreen(e.position);
  const px = e.height * tf.scale;
  const wf = e.widthFactor && e.widthFactor > 0 ? e.widthFactor : 1;
  const slant = e.oblique ? Math.tan(e.oblique) : 0;
  // %%u / %%o / %%k toggles (underline, overline, strike) are not drawn on single-line text.
  const text = e.text.includes('%%') ? e.text.replace(/%%[uUoOkK]/g, '') : e.text;
  if (px < 2.5) {
    // too small to read: draw a placeholder bar like AutoCAD's QTEXT
    const w = measured ? Math.max(measured.metrics.advance, measured.metrics.right) * tf.scale * wf : text.length * px * 0.8 * wf;
    const c = Math.cos(e.rotation);
    const sn = Math.sin(e.rotation);
    const off = measured ? measured.offset * tf.scale * wf : e.align === 'center' ? -w / 2 : e.align === 'right' ? -w : 0;
    ctx.beginPath();
    ctx.moveTo(p.x + off * c, p.y - off * sn);
    ctx.lineTo(p.x + (off + w) * c, p.y - (off + w) * sn);
    ctx.stroke();
    return;
  }
  // TrueType / OpenType text styles draw with a canvas font stack (SHX and unknown styles fall through to the strokes).
  if (drawStyledText(ctx, text === source.text ? source : { ...source, text }, tf, textStyleOf(source), geometry)) return;
  const run = measured && geometry?.shxRun?.(text, e.height, measured.appearance);
  if (run?.ok) {
    const paths = shxTextPaths(run, e, measured!.offset);
    canvasSave(ctx, () => {
      ctx.setLineDash([]); ctx.beginPath();
      for (const path of paths) {
        const from = tf.toScreen(path.from), to = tf.toScreen(path.to);
        ctx.moveTo(from.x, from.y);
        if (path.controls) {
          const first = tf.toScreen(path.controls[0]), second = tf.toScreen(path.controls[1]);
          ctx.bezierCurveTo(first.x, first.y, second.x, second.y, to.x, to.y);
        } else ctx.lineTo(to.x, to.y);
      }
      if (e.bold) ctx.lineWidth += Math.max(1, px / 12);
      if (paths.length) ctx.stroke();
    });
    return;
  }
  if (hasStrokeFont) {
    const plain = wf === 1 && slant === 0;
    const strokes = plain ? strokeText(text, e.position, e.height, e.rotation, e.align) : strokeText(text, { x: 0, y: 0 }, e.height, 0, e.align);
    const c = Math.cos(e.rotation);
    const sn = Math.sin(e.rotation);
    const world = plain
      ? (q: Point) => q
      : (q: Point) => {
          const lx = q.x * wf + q.y * slant;
          return { x: e.position.x + lx * c - q.y * sn, y: e.position.y + lx * sn + q.y * c };
        };
    ctx.beginPath();
    for (const stroke of strokes) {
      for (let i = 0; i < stroke.length; i += 1) {
        const sp = tf.toScreen(world(stroke[i]!));
        if (i === 0) ctx.moveTo(sp.x, sp.y);
        else ctx.lineTo(sp.x, sp.y);
      }
    }
    if (e.bold) {
      canvasSave(ctx, () => {
        ctx.lineWidth += Math.max(1, px / 12);
        ctx.stroke();
      });
    } else ctx.stroke();
    return;
  }
  canvasSave(ctx, () => {
    ctx.translate(p.x, p.y);
    ctx.rotate(-e.rotation);
    if (wf !== 1 || slant !== 0) ctx.transform(wf, 0, -slant, 1, 0, 0);
    ctx.font = `${e.bold ? 'bold ' : ''}${px}px "Cascadia Mono", "Consolas", "DejaVu Sans Mono", monospace`;
    ctx.textBaseline = 'alphabetic';
    ctx.textAlign = e.align;
    ctx.fillText(expandControlCodes(text), 0, 0);
  });
}

const styledParts = new WeakMap<MTextEntity, TextEntity[]>();
/** The pieces of an MTEXT carrying the MTEXT's text style (formatted runs draw with a TrueType style too). */
function styledMtextParts(e: MTextEntity, geometry?: TextGeometryContext): TextEntity[] {
  if (geometry) return mtextParts(e, geometry);
  const style = textStyleOf(e);
  if (!style) return mtextParts(e);
  let hit = styledParts.get(e);
  if (!hit) {
    hit = mtextParts(e).map((t) => withTextStyle(t, style));
    styledParts.set(e, hit);
  }
  return hit;
}

/** Draw sub-entities in their own colours (formatted MTEXT runs, leader / table / image parts). */
function drawPlotPart(ctx: CanvasRenderingContext2D, part: Entity, tf: Transform, layers: readonly Layer[], lookup: BlockLookup, style: DrawStyle, owner: Entity): void {
  const sub = { ...part, lineWeight: part.lineWeight ?? (owner.type === 'insert' ? undefined : owner.lineWeight), ...(part.color === 0 ? inheritedColor(part, owner) : {}) } as Entity;
  const childStyle = { ...style, inheritedLineweightMm: plotObjectProperties(owner, layers, style.inheritedLineweightMm).lineweightMm };
  const plotted = plottedAppearance(sub, layers, childStyle)!;
  canvasSave(ctx, () => {
    ctx.globalAlpha = (style.alpha ?? 1) * resolveAlpha(sub, layers);
    ctx.strokeStyle = style.strokeOverride ?? plotted.color;
    ctx.fillStyle = ctx.strokeStyle;
    ctx.lineWidth = style.lineWidthOverride ?? plotted.width;
    if (!style.dashed) ctx.setLineDash(resolveDash(sub, layers, tf));
    drawGeometry(ctx, sub, tf, layers, lookup, childStyle);
  });
}

function drawParts(ctx: CanvasRenderingContext2D, parts: readonly Entity[], tf: Transform, layers: readonly Layer[], lookup: BlockLookup, style: DrawStyle, owner: Entity): void {
  for (const sub of parts) {
    if (style.plot) { drawPlotPart(ctx, sub, tf, layers, lookup, style, owner); continue; }
    ctx.globalAlpha = (style.alpha ?? 1) * resolveAlpha(sub, layers);
    const subColor = style.strokeOverride ?? resolveColor(sub, layers);
    ctx.strokeStyle = subColor;
    ctx.fillStyle = subColor;
    drawGeometry(ctx, sub, tf, layers, lookup, style);
  }
}

function tracePoints(ctx: CanvasRenderingContext2D, pts: readonly Point[], tf: Transform, close: boolean): void {
  pts.forEach((q, i) => {
    const sp = tf.toScreen(q);
    if (i === 0) ctx.moveTo(sp.x, sp.y);
    else ctx.lineTo(sp.x, sp.y);
  });
  if (close) ctx.closePath();
}

function drawHatch(ctx: CanvasRenderingContext2D, e: HatchEntity, tf: Transform, layers: readonly Layer[], style: DrawStyle): void {
  if (style.plot?.usePlotStyles && hasHatchGradient(e)) style.plot.issues?.add('Gradient hatch plot-style interpretation is unverified; retained gradient colours and existing fill fallback are used.');
  const geo = hatchGeometry(e);
  if (e.solid || hasHatchGradient(e) || geo.dense) {
    ctx.beginPath();
    for (const poly of geo.polys) tracePoints(ctx, poly, tf, true);
    canvasSave(ctx, () => {
      const gradient = !style.strokeOverride && linearHatchGradientPlan(e, geo.polys);
      if (gradient) {
        const axis = linearHatchGradientAxis(gradient.frame);
        if (axis) {
          const start = tf.toScreen(axis.start), end = tf.toScreen(axis.end);
          if ([start.x, start.y, end.x, end.y].every(Number.isFinite) && g.dist(start, end) > 0) {
            const fill = ctx.createLinearGradient(start.x, start.y, end.x, end.y);
            gradient.colors.forEach((color, i) => {
              const rgb = hatchGradientColorRgb(color, (aci) => {
                const css = resolveColor({ ...e, color: aci, trueColor: undefined }, layers);
                return parseInt(css.slice(1), 16);
              });
              fill.addColorStop(i, trueColorCss(rgb!));
            });
            ctx.fillStyle = fill;
          }
        }
      }
      if (geo.dense) ctx.globalAlpha *= 0.35;
      // Selected: a lighter fill so the dashed boundary shows through.
      else if (style.dashed) ctx.globalAlpha *= 0.55;
      ctx.fill('evenodd');
    });
  } else {
    canvasSave(ctx, () => {
      if (!style.dashed) ctx.setLineDash([]);
      ctx.beginPath();
      const dots: Point[] = [];
      for (const [a, b] of geo.segments) {
        const sa = tf.toScreen(a);
        const sb = tf.toScreen(b);
        if (Math.abs(sa.x - sb.x) < 0.5 && Math.abs(sa.y - sb.y) < 0.5) {
          dots.push(sa);
          continue;
        }
        ctx.moveTo(sa.x, sa.y);
        ctx.lineTo(sb.x, sb.y);
      }
      ctx.stroke();
      for (const d of dots) ctx.fillRect(Math.round(d.x) - 0.5, Math.round(d.y) - 0.5, 1.5, 1.5);
    });
  }
  // Selected / hovered: show the boundary so a hatch is visibly picked.
  if (style.dashed || style.lineWidthOverride) {
    ctx.beginPath();
    for (const poly of geo.polys) tracePoints(ctx, poly, tf, true);
    ctx.stroke();
  }
}

function drawImage(ctx: CanvasRenderingContext2D, e: ImageEntity, tf: Transform, layers: readonly Layer[], lookup: BlockLookup, style: DrawStyle): void {
  const bmp = imageBitmap(e.path, style.imageLoader ?? renderSettings.imageLoader);
  const parts = imageParts(e);
  if (!bmp) {
    drawParts(ctx, parts, tf, layers, lookup, style, e);
    return;
  }
  canvasSave(ctx, () => {
    ctx.beginPath();
    tracePoints(ctx, imageBoundary(e), tf, true);
    ctx.clip();
    const topLeft = g.add(e.position, g.scale(e.v, e.size.y));
    const p0 = tf.toScreen(topLeft);
    const px = g.sub(tf.toScreen(g.add(topLeft, e.u)), p0);
    const py = g.sub(tf.toScreen(g.sub(topLeft, e.v)), p0);
    ctx.transform(px.x, px.y, py.x, py.y, p0.x, p0.y);
    if (e.fade) ctx.globalAlpha *= Math.max(0, 1 - e.fade / 100);
    ctx.drawImage(bmp, 0, 0, e.size.x, e.size.y);
  });
  // Frame only (the file name is drawn when the bitmap is missing).
  drawParts(ctx, parts.slice(0, 1), tf, layers, lookup, style, e);
}

/**
 * An underlay placement, drawn by consuming the model's display list
 * (core/underlay.ts underlayDisplayList) — the same op list the plot path
 * is specified against (RULING-P28 C4). With no resolved definition the
 * placement is the generated frame + cross parts and NO label (a label is
 * only ever a real definition's stored path). With a definition: frame /
 * clip-frame / cross / label ops become primitives drawn like any other
 * parts; the image op draws the rasterized page bitmap into the frame
 * quad (the drawImage transform technique), with the placement fade.
 * Without a content source (v0.6.4: none is installed), the definition
 * comes from the drawing's own sibling (underlayDefinitionContent), so the
 * frame still carries the file-name label.
 */
function drawUnderlay(ctx: CanvasRenderingContext2D, e: UnderlayEntity, tf: Transform, layers: readonly Layer[], lookup: BlockLookup, style: DrawStyle): void {
  const res = (style.underlaySource ?? renderSettings.underlaySource)?.(e) ?? underlayDefinitionContent(e, style.underlayDefinitions ?? renderSettings.underlayDefinitions);
  if (!res?.definition) {
    drawParts(ctx, underlayParts(e), tf, layers, lookup, style, e);
    return;
  }
  const def = res.definition;
  const content = res.image ? (res.page ?? { width: res.image.width, height: res.image.height }) : undefined;
  const ops = underlayDisplayList(underlayPlacementOf(e), def, content);
  const styleProps = { layer: e.layer, color: e.color, linetype: e.linetype, lineWeight: e.lineWeight };
  for (const op of ops) {
    if (op.op === 'image' && res.image) {
      const [ll, lr, ur, ul] = op.corners;
      if (!ll || !lr || !ur || !ul) continue;
      const bmp = res.image.bitmap;
      const W = res.image.width;
      const H = res.image.height;
      // Clip (design 5.2): the clip-frame op clips ONLY this raster, inside
      // its own save/restore; frame / clip-frame / cross / label ops draw
      // outside the clipped context. The display list itself is unchanged.
      const clipOp = ops.find((o) => o.op === 'clip-frame');
      canvasSave(ctx, () => {
        if (clipOp) {
          ctx.beginPath();
          clipOp.points.forEach((p, i) => {
            const s = tf.toScreen(p);
            if (i === 0) ctx.moveTo(s.x, s.y);
            else ctx.lineTo(s.x, s.y);
          });
          ctx.closePath();
          ctx.clip();
        }
        canvasSave(ctx, () => {
          const o = tf.toScreen(ul);
          const ax = g.sub(tf.toScreen(ur), o);
          const ay = g.sub(tf.toScreen(ll), o);
          ctx.transform(ax.x / W, ax.y / W, ay.x / H, ay.y / H, o.x, o.y);
          if (e.fade) ctx.globalAlpha *= Math.max(0, 1 - e.fade / 100);
          ctx.drawImage(bmp, 0, 0, W, H);
        });
      });
    } else if (op.op === 'frame' || op.op === 'clip-frame') {
      drawParts(ctx, [{ ...styleProps, id: `${e.id}:${op.op}`, type: 'polyline', points: [...op.points], closed: true }], tf, layers, lookup, style, e);
    } else if (op.op === 'cross') {
      const [a, b, c, d] = op.points;
      if (!a || !b || !c || !d) continue;
      drawParts(ctx, [
        { ...styleProps, id: `${e.id}:x1`, type: 'line', a, b },
        { ...styleProps, id: `${e.id}:x2`, type: 'line', a: c, b: d },
      ], tf, layers, lookup, style, e);
    } else if (op.op === 'label') {
      const frame = ops.find((o) => o.op === 'frame');
      const ys = frame ? frame.points.map((p) => p.y) : [];
      const frameH = ys.length ? Math.max(...ys) - Math.min(...ys) : 0;
      const th = frameH > 0 ? frameH * 0.08 : 0.1;
      drawParts(ctx, [{ ...styleProps, id: `${e.id}:n`, type: 'text', position: op.at, text: op.text, height: th, rotation: e.rotation, align: 'left' }], tf, layers, lookup, style, e);
    }
  }
}

/** PDMODE point marker. Size: PDSIZE > 0 absolute, 0 = 5% of view height, < 0 = percent of view height. */
function drawPointMarker(ctx: CanvasRenderingContext2D, pos: Point, tf: Transform): void {
  const s = tf.toScreen(pos);
  const mode = renderSettings.pdmode;
  const viewH = tf.viewBounds ? (tf.viewBounds.max.y - tf.viewBounds.min.y) * tf.scale : 600;
  const size = renderSettings.pdsize > 0 ? renderSettings.pdsize * tf.scale : (viewH * (renderSettings.pdsize < 0 ? -renderSettings.pdsize : 5)) / 100;
  const h = Math.max(3, size / 2);
  const x = Math.round(s.x) + 0.5;
  const y = Math.round(s.y) + 0.5;
  const shape = mode % 32;
  const addCircle = (mode & 32) !== 0;
  const addSquare = (mode & 64) !== 0;
  ctx.setLineDash([]);
  ctx.beginPath();
  if (shape === 1) {
    /* nothing */
  } else if (shape === 2) {
    ctx.moveTo(x - h, y);
    ctx.lineTo(x + h, y);
    ctx.moveTo(x, y - h);
    ctx.lineTo(x, y + h);
  } else if (shape === 3) {
    ctx.moveTo(x - h, y - h);
    ctx.lineTo(x + h, y + h);
    ctx.moveTo(x - h, y + h);
    ctx.lineTo(x + h, y - h);
  } else if (shape === 4) {
    ctx.moveTo(x, y);
    ctx.lineTo(x, y - h);
  } else {
    // 0: a dot
    ctx.rect(x - 1, y - 1, 2, 2);
    ctx.fill();
  }
  if (addCircle) ctx.arc(x, y, h, 0, Math.PI * 2);
  if (addSquare) ctx.rect(x - h, y - h, 2 * h, 2 * h);
  ctx.stroke();
}

function drawGeometry(
  ctx: CanvasRenderingContext2D,
  e: Entity,
  tf: Transform,
  layers: readonly Layer[],
  lookup: BlockLookup,
  style: DrawStyle,
): void {
  switch (e.type) {
    case 'line': {
      const a = tf.toScreen(e.a);
      const b = tf.toScreen(e.b);
      ctx.beginPath();
      ctx.moveTo(a.x, a.y);
      ctx.lineTo(b.x, b.y);
      ctx.stroke();
      break;
    }
    case 'circle': {
      const c = tf.toScreen(e.center);
      ctx.beginPath();
      ctx.arc(c.x, c.y, e.radius * tf.scale, 0, Math.PI * 2);
      if (e.filled) ctx.fill();
      else ctx.stroke();
      break;
    }
    case 'arc': {
      const c = tf.toScreen(e.center);
      // screen Y is flipped, so a CCW world arc is drawn CW-in-canvas terms with negated angles
      ctx.beginPath();
      if (g.normAngle(e.endAngle - e.startAngle) < g.EPS) ctx.arc(c.x, c.y, e.radius * tf.scale, 0, Math.PI * 2);
      else ctx.arc(c.x, c.y, e.radius * tf.scale, -e.startAngle, -e.endAngle, true);
      ctx.stroke();
      break;
    }
    case 'polyline': {
      if (e.points.length === 0) break;
      if ((e.widths || e.widthFrame) && !e.filled) {
        const geometry = polylineWidthGeometry(e);
        const dashed = typeof ctx.getLineDash === 'function' && ctx.getLineDash().length > 0;
        const path = (points: readonly Point[], closed = false) => {
          points.forEach((point, index) => { const p = tf.toScreen(point); if (index === 0) ctx.moveTo(p.x, p.y); else ctx.lineTo(p.x, p.y); });
          if (closed) ctx.closePath();
        };
        if (!geometry.polygons.length) {
          ctx.beginPath();
          geometry.thin.forEach((spine) => path(spine));
          ctx.stroke();
          break;
        }
        if (dashed) {
          const masks = (target: CanvasRenderingContext2D) => {
            const addPath = (points: readonly Point[], closed = false) => {
              points.forEach((point, index) => { const p = tf.toScreen(point); if (index === 0) target.moveTo(p.x, p.y); else target.lineTo(p.x, p.y); });
              if (closed) target.closePath();
            };
            for (const { polygon, spines } of geometry.strokes) {
              canvasSave(target, () => {
                target.beginPath(); addPath(polygon, true); target.clip();
                target.lineWidth = Math.min(Number.MAX_VALUE, geometry.maxWidth * tf.scale);
                target.beginPath(); spines.forEach((spine) => addPath(spine)); target.stroke();
              });
            }
            if (geometry.thin.length) {
              target.beginPath(); geometry.thin.forEach((spine) => addPath(spine)); target.stroke();
            }
          };
          if (ctx.globalAlpha < 1 && geometry.strokes.length + Number(geometry.thin.length > 0) > 1) paintOpacityGroup(ctx, [...geometry.polygons, ...geometry.thin], (point) => tf.toScreen(point), masks);
          else masks(ctx);
          break;
        }
        // One paint operation composites the complete entity alpha once, including joins
        // and explicit-zero segments drawn at the current display lineweight.
        const thinWidth = ctx.lineWidth / tf.scale;
        const polygons = [...geometry.polygons, ...strokeOutlinePolygons(geometry.thin, thinWidth)];
        ctx.beginPath();
        polygons.forEach((polygon) => path(polygon, true));
        ctx.fill();
        break;
      }
      strokePolyline(ctx, e, tf);
      if (e.filled && e.closed) {
        ctx.fill();
        break;
      }
      if (e.width && e.width > 0) {
        const px = e.width * tf.scale;
        if (px > (style.lineWidthOverride ?? 1)) {
          canvasSave(ctx, () => {
            ctx.lineWidth = px;
            ctx.lineJoin = 'round';
            ctx.lineCap = 'butt';
            ctx.stroke();
          });
          break;
        }
      }
      ctx.stroke();
      break;
    }
    case 'text':
      drawText(ctx, e, tf, lookup.textGeometry);
      break;
    case 'insert': {
      for (const sub of style.plot ? expandPlotInsert(e, lookup, layers) : explodeInsert(e, lookup)) {
        if (style.hidden?.has(sub.layer)) continue;
        if (style.plot) { drawPlotPart(ctx, sub, tf, layers, lookup, style, e); continue; }
        ctx.globalAlpha = (style.alpha ?? 1) * resolveAlpha(sub, layers);
        const subColor = style.strokeOverride ?? resolveColor(sub, layers);
        ctx.strokeStyle = subColor;
        ctx.fillStyle = subColor;
        if (!style.dashed) ctx.setLineDash(resolveDash(sub, layers, tf));
        drawGeometry(ctx, sub, tf, layers, lookup, style);
      }
      break;
    }
    case 'ellipse': {
      const c = tf.toScreen(e.center);
      const a = g.len(e.majorAxis) * tf.scale;
      const b = a * e.ratio;
      const rot = Math.atan2(e.majorAxis.y, e.majorAxis.x);
      ctx.beginPath();
      if (isFullEllipse(e)) ctx.ellipse(c.x, c.y, a, b, -rot, 0, Math.PI * 2);
      else ctx.ellipse(c.x, c.y, a, b, -rot, -e.startParam, -(e.startParam + ellipseSweep(e)), true);
      ctx.stroke();
      break;
    }
    case 'point':
      drawPointMarker(ctx, e.position, tf);
      break;
    case 'xline':
    case 'ray': {
      const ends = constructionLineEnds(e, tf);
      if (!ends) break;
      const a = tf.toScreen(ends[0]);
      const b = tf.toScreen(ends[1]);
      ctx.beginPath();
      ctx.moveTo(a.x, a.y);
      ctx.lineTo(b.x, b.y);
      ctx.stroke();
      break;
    }
    case 'mtext': {
      if (e.background) {
        const background = e.background;
        canvasSave(ctx, () => {
          const maskEntity = { ...e, color: background.color, trueColor: background.trueColor, colorLayer: background.colorLayer };
          ctx.fillStyle = background.flags & 2 ? (colorDisplay.paper ? '#ffffff' : colorDisplay.background) : plottedAppearance(maskEntity, layers, style)?.color ?? resolveColor(maskEntity, layers);
          for (const mask of mtextMasks(e, lookup.textGeometry)) {
            ctx.beginPath();
            tracePoints(ctx, mask, tf, true);
            if (hasMTextFill(e)) ctx.fill();
            if (hasMTextFrame(e)) ctx.stroke();
          }
        });
      }
      const pieces = styledMtextParts(e, lookup.textGeometry);
      const lines = mtextDecorations(e, lookup.textGeometry);
      if (!style.plot && lines.length === 0 && pieces.every((t) => t.color === e.color && t.trueColor === e.trueColor)) {
        for (const t of pieces) drawText(ctx, t, tf, lookup.textGeometry);
      } else drawParts(ctx, [...pieces, ...lines], tf, layers, lookup, style, e);
      break;
    }
    case 'dimension': {
      if (style.plot) { drawParts(ctx, dimensionParts(e, lookup.textGeometry), tf, layers, lookup, style, e); break; }
      // DIMCLRD / DIMCLRE / DIMCLRT: parts drawn in a style colour get it; the rest keep the
      // dimension's own colour (true colour included) already set on the context.
      const ownStroke = ctx.strokeStyle;
      const ownFill = ctx.fillStyle;
      for (const part of dimensionParts(e, lookup.textGeometry)) {
        ctx.globalAlpha = (style.alpha ?? 1) * resolveAlpha(part, layers);
        const own = style.strokeOverride !== undefined || part.color === e.color;
        ctx.strokeStyle = own ? ownStroke : resolveColor(part, layers);
        ctx.fillStyle = own ? ownFill : ctx.strokeStyle;
        drawGeometry(ctx, part, tf, layers, lookup, style);
      }
      ctx.strokeStyle = ownStroke;
      ctx.fillStyle = ownFill;
      break;
    }
    case 'spline': {
      const pts = splinePoints(e);
      if (pts.length < 2) break;
      ctx.beginPath();
      tracePoints(ctx, pts, tf, false);
      ctx.stroke();
      break;
    }
    case 'hatch':
      drawHatch(ctx, e, tf, layers, style);
      break;
    case 'leader':
      drawParts(ctx, leaderParts(e, lookup.textGeometry).filter((p) => !style.hidden?.has(p.layer) && layers.find((l) => l.name === p.layer)?.visible !== false), tf, layers, lookup, style, e);
      break;
    case 'table':
      drawParts(ctx, tableParts(e, lookup.textGeometry), tf, layers, lookup, style, e);
      break;
    case 'image':
      drawImage(ctx, e, tf, layers, lookup, style);
      break;
    case 'underlay':
      drawUnderlay(ctx, e, tf, layers, lookup, style);
      break;
  }
}

/** Draw a set of entities into an arbitrary canvas fitted to their bounds (for previews). */
export function drawPreview(
  ctx: CanvasRenderingContext2D,
  entities: readonly Entity[],
  layers: readonly Layer[],
  lookup: BlockLookup,
  width: number,
  height: number,
  color = '#e6e6e6',
  padding = 8,
): void {
  let b: g.Bounds | null = null;
  for (const e of entities) b = g.unionBounds(b, entityBounds(e, lookup));
  if (!b) return;
  const bw = Math.max(b.max.x - b.min.x, 1e-6);
  const bh = Math.max(b.max.y - b.min.y, 1e-6);
  const s = Math.min((width - padding * 2) / bw, (height - padding * 2) / bh);
  const cx = (b.min.x + b.max.x) / 2;
  const cy = (b.min.y + b.max.y) / 2;
  const tf: Transform = {
    scale: s,
    toScreen: (p) => ({ x: width / 2 + (p.x - cx) * s, y: height / 2 - (p.y - cy) * s }),
  };
  for (const e of entities) drawEntity(ctx, e, tf, layers, lookup, { strokeOverride: color, lineWidthOverride: 1 });
}
