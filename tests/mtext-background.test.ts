// Hand-written native groups from the public Autodesk MTEXT reference; never generated by JCad.
const source = readFileSync(new URL('./fixtures/interchange/r2018-mtext-background.dxf', import.meta.url), 'utf8').replace(/\r\n/g, '\n');
const sample = () => readDxf(source);
function mask(name: string) { return sample().entities.find((e): e is MTextEntity => e.type === 'mtext' && e.text.startsWith(name))!; }
const lookup = () => undefined;
const layers: Layer[] = [{ name: '0', color: 7, visible: true, locked: false, lineWeight: 0.25 }];
const version = (s: string) => sniffDxfHeader(new TextEncoder().encode(s)).acadver;

/** Native record inspection is independent of the JCad importer. */
function records(dxf: string) {
  const lines = dxf.trimEnd().split(/\r?\n/); const out: Array<Map<number, string>> = [];
  let row: Map<number, string> | null = null;
  for (let i = 0; i < lines.length; i += 2) {
    const code = Number(lines[i]); const value = lines[i + 1]!;
    if (code === 0) { if (row) out.push(row); row = value === 'MTEXT' ? new Map() : null; }
    else row?.set(code, value);
  }
  if (row) out.push(row);
  return out;
}

function screen(e: MTextEntity | LeaderEntity, hidden: ReadonlySet<string> = new Set()) {
  type Paint = { kind: 'fill' | 'stroke'; color: unknown; points: number[][] };
  const paints: Paint[] = []; let points: number[][] = [];
  const state: Record<string, unknown> = { lineWidth: 1, globalAlpha: 1 }; const saved: Array<Record<string, unknown>> = [];
  const api: Record<string, unknown> = {
    save: () => saved.push({ ...state }), restore: () => { const previous = saved.pop(); if (previous) Object.assign(state, previous); },
    beginPath: () => { points = []; }, moveTo: (x: number, y: number) => points.push([x, y]), lineTo: (x: number, y: number) => points.push([x, y]),
    fill: () => paints.push({ kind: 'fill', color: state.fillStyle, points: [...points] }),
    stroke: () => paints.push({ kind: 'stroke', color: state.strokeStyle, points: [...points] }), getLineDash: () => [],
  };
  const context = new Proxy(state, { get: (o, k) => api[String(k)] ?? o[String(k)] ?? (() => {}), set: (o, k, v) => { o[String(k)] = v; return true; } }) as unknown as CanvasRenderingContext2D;
  drawEntity(context, e, { toScreen: (p) => p, scale: 10 }, layers, lookup, { hidden });
  return paints;
}
function pdf(e: MTextEntity, monochrome = false) {
  const state = new Drawing({ entities: [e], layers }).snapshot;
  const bytes = vectorPdf([{ width: 300, height: 300, label: 'Mask', groups: [{ entities: [e], k: 1, e: 0, f: 0, hidden: new Set(), ltUnit: 1, annoFactor: 1 }] }], drawingContext(state, lookup), { mode: monochrome ? 'monochrome' : 'color', lineweights: true, usePlotStyles: true });
  const info = parsePdfBasics(bytes); expect(info.errors).toEqual([]);
  return parseContentStream(pageContents(info, (b) => new Uint8Array(inflateSync(b)))[0]!);
}

describe('native MTEXT background masks', () => {
  it('keeps native ACI, RGB, named color, fill flags and scale independently from text appearance', () => {
    const s = sample(); expect(s.entities.filter((e) => e.type === 'mtext')).toHaveLength(7);
    expect(mask('ACI MASK').background).toEqual({ flags: 1, scale: 1.5, color: 1 }); // no reference-width group41
    const rgb = mask('RGB');
    expect(rgb.background).toEqual({ flags: 1, scale: 2, color: 3, trueColor: 0x123456, colorName: 'Example Book$Slate', transparency: 0 });
    expect(rgb.trueColor).toBeUndefined(); expect(rgb.rotation).toBeCloseTo(Math.PI / 2);
    expect(mask('WINDOW').background?.flags).toBe(3);
    expect(mask('FRAME').background?.flags).toBe(16);
    expect(mtextMasks(mask('OFF'))).toEqual([]);
    expect(JSON.stringify(importReportOf(s))).not.toContain('background fill is not kept');
  });

  it('writes native groups, chooses only the required DXF version and retains metadata on reopen', () => {
    const s = sample(); const written = writeDxf(s); const rows = records(written);
    expect(version(written)).toBe('AC1032');
    const rgb = rows.find((r) => r.get(1)?.startsWith('RGB'))!;
    expect([90, 45, 63, 421, 431, 441].map((c) => rgb.get(c))).toEqual(['1', '2', '3', '1193046', 'Example Book$Slate', '0']);
    const frame = rows.find((r) => r.get(1) === 'FRAME')!;
    expect(frame.get(90)).toBe('16');
    expect(frame.get(45)).toBe('1.5'); expect(frame.get(63)).toBe('256');
    for (const code of [421, 431, 441]) expect(frame.has(code)).toBe(false);
    expect(version(writeDxf({ ...s, entities: [mask('ACI MASK')] }))).toBe('AC1021');
    expect(version(writeDxf({ ...s, entities: [{ ...mask('ACI MASK'), background: undefined }] }))).toBe('AC1015');
    const reopened = readDxf(decodeDxfBytes(new TextEncoder().encode(written)).text);
    for (const e of s.entities) if (e.type === 'mtext' && e.background?.flags) expect(reopened.entities.find((p) => p.type === 'mtext' && p.text === e.text)).toMatchObject({ background: e.background });
  });

  it('uses the text-height padding for rotated masks, bounds, selection, transforms and undo', () => {
    const e = mask('ACI MASK'); const p = mtextMasks(e)[0]!;
    expect(p).toEqual([{ x: -1, y: -3 }, { x: textWidth(e.text, 2) + 1, y: -3 }, { x: textWidth(e.text, 2) + 1, y: 1 }, { x: -1, y: 1 }]);
    const b = entityBounds(e, lookup)!; expect(b.min).toEqual({ x: -1, y: -3 }); expect(b.max.y).toBe(1);
    expect(distanceToEntity({ x: -0.5, y: 0.5 }, e, lookup)).toBe(0);
    const moved = translateEntity(e, { x: 5, y: 10 }) as MTextEntity;
    expect(mtextMasks(moved)[0]![0]).toEqual({ x: 4, y: 7 });
    const rotated = rotateEntity(e, { x: 0, y: 0 }, Math.PI / 2) as MTextEntity;
    expect(mtextMasks(rotated)[0]![0]!.x).toBeCloseTo(3); expect(mtextMasks(rotated)[0]![0]!.y).toBeCloseTo(-1);
    const scaled = scaleEntityBy(e, { x: 0, y: 0 }, 2) as MTextEntity;
    expect(mtextMasks(scaled)[0]![0]).toEqual({ x: -2, y: -6 }); expect(scaled.background).toEqual(e.background);
    const drawing = new Drawing({ entities: [e] }); drawing.replaceEntities([moved]); drawing.undo();
    expect(mtextMasks(drawing.entities[0] as MTextEntity)).toEqual(mtextMasks(e));
  });

  it('draws an opaque mask before the glyphs and keeps screen and vector PDF corners identical', () => {
    const e = mask('RGB'); const paints = screen(e);
    expect(paints[0]?.kind).toBe('fill'); expect(paints[0]?.color).toBe('#123456');
    expect(paints.slice(1).every((p) => p.kind === 'stroke' && p.color === '#ffffff')).toBe(true);
    const content = pdf(e); expect(content.errors).toEqual([]);
    const filled = content.ops.findIndex((op) => op.op === 'f'); const glyph = content.ops.findIndex((op) => op.op === 'S');
    expect(filled).toBeGreaterThan(0); expect(glyph).toBeGreaterThan(filled);
    const points = content.ops.slice(0, filled).filter((op) => op.op === 'm' || op.op === 'l').map((op) => op.args.map(Number));
    expect(points).toHaveLength(4);
    for (let i = 0; i < 4; i++) for (let j = 0; j < 2; j++) expect(points[i]![j]).toBeCloseTo(paints[0]!.points[i]![j]!, 2);
  });

  it('window-color masks follow the viewport, become white on paper and remain white under monochrome plotting', () => {
    const e = mask('WINDOW'); const previous = { ...colorDisplay };
    try {
      colorDisplay.background = '#332211'; colorDisplay.paper = false; expect(screen(e)[0]?.color).toBe('#332211');
      colorDisplay.paper = true; expect(screen(e)[0]?.color).toBe('#ffffff');
      const content = pdf(e, true); const firstFill = content.ops.findIndex((op) => op.op === 'f');
      const colors = content.ops.slice(0, firstFill).filter((op) => op.op === 'rg');
      expect(colors[colors.length - 1]?.args.map(Number)).toEqual([1, 1, 1]);
    } finally { Object.assign(colorDisplay, previous); }
  });

  it('frame-only masks have no fill and explicit column masks do not cover the gutter, including reversed flow', () => {
    expect(screen(mask('FRAME')).every((p) => p.kind === 'stroke')).toBe(true);
    expect(pdf(mask('FRAME')).counts.f ?? 0).toBe(0);
    expect(pdf(mask('FILL + FRAME')).counts.B).toBe(1);
    const e = mask('COLUMN'); expect(e.columns).toMatchObject({ count: 2, width: 6, gutter: 3 });
    for (const reversed of [false, true]) {
      const masks = mtextMasks({ ...e, columns: { ...e.columns!, reversed } }); expect(masks).toHaveLength(2);
      const extents = masks.map((p) => [Math.min(...p.map((q) => q.x)), Math.max(...p.map((q) => q.x))]).sort((a, b) => a[0]! - b[0]!);
      expect(extents[0]![1]).toBeLessThanOrEqual(126); expect(extents[1]![0]).toBeGreaterThanOrEqual(129);
    }
    const annotated = annotativeEntity(e, 2) as MTextEntity;
    expect(annotated.columns).toMatchObject({ width: 12, gutter: 6, heights: [40, 40] });
    const scaled = mtextMasks(annotated).map((p) => p.map((q) => ({ x: (q.x - e.position.x) / 2 + e.position.x, y: (q.y - e.position.y) / 2 + e.position.y })));
    const original = mtextMasks(e);
    for (let i = 0; i < scaled.length; i++) for (let j = 0; j < 4; j++) {
      expect(scaled[i]![j]!.x).toBeCloseTo(original[i]![j]!.x, 10);
      expect(scaled[i]![j]!.y).toBeCloseTo(original[i]![j]!.y, 10);
    }
  });

  it('resolves a ByBlock mask independently of its text and bakes inherited layer color on explode', () => {
    const e: MTextEntity = { ...mask('ACI MASK'), color: 2, background: { flags: 1, scale: 1.5, color: 0 } };
    const ins: InsertEntity = { type: 'insert', id: 'ins', layer: 'MASK', color: 'ByLayer', position: { x: 10, y: 20 }, block: 'B', scale: 2, rotation: 0, attributes: {} };
    const expanded = explodeInsert(ins, () => ({ name: 'B', basePoint: { x: 0, y: 0 }, entities: [e], attributes: [] }))[0] as MTextEntity;
    expect(expanded.color).toBe(2); expect(expanded.background).toMatchObject({ color: 'ByLayer', colorLayer: 'MASK' });
    const baked = bakeInheritedColor(expanded, [{ ...layers[0]!, name: 'MASK', color: 4, trueColor: 0xabcdef }]);
    expect(baked.background).toMatchObject({ color: 4, trueColor: 0xabcdef }); expect(baked.background?.colorLayer).toBeUndefined();
  });

  it('retains exposed DWG RGB masks and reports fields the installed reader cannot preserve', () => {
    const payload = { header: {}, layers: [], blocks: [], entities: [{ type: 'MTEXT', handle: 'A2', layer: '0', insertionPoint: { x: 0, y: 0, z: 0 }, text: 'DWG RGB', textHeight: 2, rectWidth: 20, attachmentPoint: 1, backgroundFill: 1, fillBoxScale: 2, backgroundFillColor: 0xc3123456, backgroundFillTransparency: 0 }] } as unknown as DwgImportPayload;
    const result = convertDwg(payload); const e = result.state.entities[0] as MTextEntity;
    expect(e.background).toMatchObject({ flags: 1, scale: 2, trueColor: 0x123456 });
    expect(JSON.stringify(result.report)).toMatch(/background.*(reader|color|index)/i);
  });

  it('uses preserved native CMC indexes and book identities rather than treating an ACI payload as RGB', () => {
    for (const [data, expected] of [
      [{ method: 0xc2, index: 1, rgb: 0xc2000001 }, { color: 1 }],
      [{ method: 0xc3, index: 256, rgb: 0xc3123456, bookName: 'Example Book', name: 'Slate' }, { color: 'ByLayer', trueColor: 0x123456, colorName: 'Example Book$Slate' }],
      [{ method: 0xc1, index: 0, rgb: 0xc1000000 }, { color: 0 }],
    ] as const) {
      const payload = { header: {}, layers: [], blocks: [], entities: [{ type: 'MTEXT', handle: 'A2', layer: '0', insertionPoint: { x: 0, y: 0, z: 0 }, text: 'DWG', textHeight: 2, rectWidth: 20, attachmentPoint: 1, backgroundFill: 1, fillBoxScale: 1.5, backgroundFillColor: data.rgb, backgroundFillColorData: data }] } as unknown as DwgImportPayload;
      const result = convertDwg(payload); const e = result.state.entities[0] as MTextEntity;
      expect(e.background).toEqual({ flags: 1, scale: 1.5, ...expected });
      expect(JSON.stringify(result.report)).not.toContain('original ACI index');
    }
  });

  it('reports the pinned native reader scale defect without manufacturing a bogus color or transparency', () => {
    const payload = { header: {}, layers: [], blocks: [], entities: [{ type: 'MTEXT', handle: 'DEFECT', layer: '0', insertionPoint: { x: 0, y: 0, z: 0 }, text: 'NATIVE READER LIMIT', textHeight: 2, rectWidth: 20, attachmentPoint: 1, backgroundFill: 1, fillBoxScale: 0, backgroundFillColor: 0xc2560804, backgroundFillColorData: { index: 256, rgb: 0xc2560804, method: 0xc2, name: 'unusable' }, backgroundFillTransparency: 256 }] } as unknown as DwgImportPayload;
    const result = convertDwg(payload); const e = result.state.entities[0] as MTextEntity;
    expect(e.background).toEqual({ flags: 1, scale: 1.5, color: 'ByLayer' });
    expect(JSON.stringify(result.report)).toMatch(/background.*(scale|reader)/i);
    expect(geometryProblem(e)).toBeNull();
  });

  it('keeps masks carried by associated LEADER annotations through DXF/DWG import, transforms and export', () => {
    const nativeLeader = [0, 'LEADER', 5, 'B1', 100, 'AcDbEntity', 8, 'LEADERS', 100, 'AcDbLeader', 71, 1, 72, 0, 76, 2, 10, -10, 20, -10, 10, 0, 20, 0, 340, 'A1'].join('\n');
    const colored = source.replace('62\n7\n100\nAcDbMText\n10\n0', '62\n3\n420\n1122867\n100\nAcDbMText\n10\n0');
    const s = readDxf(colored.replace('0\nENDSEC\n0\nEOF', `${nativeLeader}\n0\nENDSEC\n0\nEOF`));
    const leader = s.entities.find((e): e is LeaderEntity => e.type === 'leader')!;
    expect(leader.textBackground).toEqual({ flags: 1, scale: 1.5, color: 1 }); expect(leader.textLayer).toBe('0');
    expect(leader.textAppearance).toMatchObject({ color: 3, trueColor: 0x112233 });
    expect(s.entities.some((e) => e.type === 'mtext' && e.text === 'ACI MASK')).toBe(false);
    const attached = leaderParts(leader).find((e): e is MTextEntity => e.type === 'mtext')!;
    expect(attached).toMatchObject({ color: 3, trueColor: 0x112233 });
    expect(screen(attached)[0]?.color).toBe('#ff0000'); expect(pdf(attached).counts.f).toBe(1);
    expect(screen(leader, new Set(['0'])).some((p) => p.kind === 'fill' && p.color === '#ff0000')).toBe(false);
    const moved = translateEntity(leader, { x: 3, y: 4 }) as LeaderEntity;
    expect(leaderParts(moved).find((e): e is MTextEntity => e.type === 'mtext')?.background).toEqual(attached.background);
    const scaled = scaleEntityBy(leader, { x: 0, y: 0 }, 2) as LeaderEntity;
    expect((leaderParts(scaled).find((e): e is MTextEntity => e.type === 'mtext')!).height).toBe(4);
    const written = writeDxf({ ...s, entities: [leader] }); expect(version(written)).toBe('AC1021');
    expect(records(written)[0]?.get(90)).toBe('1'); expect(records(written)[0]?.get(63)).toBe('1');
    const reopened = readDxf(written).entities.find((e): e is LeaderEntity => e.type === 'leader')!;
    expect(reopened.textBackground).toEqual(leader.textBackground); expect(reopened.textLayer).toBe('0');
    const payload = { header: {}, layers: [], blocks: [], entities: [
      { type: 'LEADER', handle: 'B1', layer: 'LEADERS', vertices: [{ x: -10, y: -10 }, { x: 0, y: 0 }], associatedAnnotation: 'A1' },
      { type: 'MTEXT', handle: 'A1', layer: 'NOTES', insertionPoint: { x: 0, y: 0, z: 0 }, text: 'DWG MASK', textHeight: 2, rectWidth: 20, attachmentPoint: 1, lineSpacing: 1.25, backgroundFill: 1, fillBoxScale: 1.5, backgroundFillColor: 0xc3000011, backgroundFillColorData: { method: 0xc3, index: 256, rgb: 0xc3000011 } },
    ] } as unknown as DwgImportPayload;
    const dwg = convertDwg(payload).state;
    expect(dwg.entities).toHaveLength(1);
    expect(dwg.entities[0]).toMatchObject({ type: 'leader', textLayer: 'NOTES', textLineSpacing: 1.25, textBackground: { flags: 1, trueColor: 0x11 } });
    expect(dwg.layers.map((l) => l.name)).toContain('NOTES');
    expect(geometryProblem({ ...leader, textBackground: { flags: 1, scale: 999, color: 1 } })).toContain('background scale');
  });

  it('captures native CMC metadata through the pinned converter boundary for both model and block MTEXT', () => {
    // Simulate its documented object -> common entity -> entity-tio calls, with distinct handles.
    const raw = new Map([[1, { index: 1, method: 0xc2, rgb: 0xc2000001 }], [2, { index: 256, method: 0xc3, rgb: 0xc3123456, name: 'Slate', book_name: 'Book' }]]);
    const instance = {
      dwg_object_to_entity: (object: number) => object + 100,
      dwg_object_to_entity_tio: (object: number) => object + 200,
      dwg_dynapi_entity_data: (tio: number, field: string) => field === 'bg_fill_color' ? raw.get(tio - 200) : undefined,
      dwg_object_entity_get_handle_object: (entity: number) => ({ value: entity - 100 + 0xa0 }),
    } as unknown as Parameters<typeof convertDwgMTextDatabase>[0];
    const database = convertDwgMTextDatabase(instance, 0 as Parameters<typeof convertDwgMTextDatabase>[1], (reader) => {
      for (const object of [1, 2]) { reader.dwg_object_to_entity(object); const tio = reader.dwg_object_to_entity_tio(object); reader.dwg_dynapi_entity_data(tio, 'bg_fill_color'); }
      return { entities: [{ type: 'MTEXT', handle: 'A1' }], tables: { BLOCK_RECORD: { entries: [{ entities: [{ type: 'MTEXT', handle: 'A2' }] }] } } } as unknown as ReturnType<typeof convertDwgMTextDatabase>;
    });
    expect(database.entities[0]).toMatchObject({ backgroundFillColorData: { index: 1, method: 0xc2, rgb: 0xc2000001 } });
    expect(database.tables.BLOCK_RECORD.entries[0]?.entities[0]).toMatchObject({ backgroundFillColorData: { index: 256, method: 0xc3, rgb: 0xc3123456, name: 'Slate', bookName: 'Book' } });
  });

  it('rejects malformed mask geometry and reports unsupported native transparency rather than applying it', () => {
    const invalid = readDxf(source.replace('45\n1.5\n63\n1', '45\n999\n63\n1'));
    expect(invalid.entities.some((e) => e.type === 'mtext' && e.text === 'ACI MASK')).toBe(false);
    expect(JSON.stringify(importReportOf(invalid))).toContain('background scale');
    const transparent = readDxf(source.replace('441\n0', '441\n33554496'));
    expect(JSON.stringify(importReportOf(transparent))).toMatch(/background transparency/i);
    expect((transparent.entities.find((e) => e.type === 'mtext' && e.text.startsWith('RGB')) as MTextEntity).background?.transparency).toBe(33554496);
    expect(geometryProblem({ ...mask('RGB'), background: { flags: 1, scale: 1.5, color: 1, trueColor: Infinity } })).toContain('not a finite number');
    expect(geometryProblem({ ...mask('RGB'), height: Number.MAX_VALUE, background: { flags: 1, scale: 5, color: 1 } })).toContain('background padding');
    const overflowing = { ...mask('RGB'), position: { x: Number.MAX_VALUE, y: Number.MAX_VALUE }, height: Number.MAX_VALUE };
    expect(mtextBackgroundPolygons(overflowing, textWidth).every((p) => p.every((q) => Number.isFinite(q.x) && Number.isFinite(q.y)))).toBe(true);
  });

  it('modern DXF exports keep supplementary Unicode intact across MTEXT chunk boundaries', () => {
    const text = `${'a'.repeat(249)}😀 tail`; const e = { ...mask('ACI MASK'), text, width: 0 };
    const written = writeDxf({ ...sample(), entities: [e] });
    const reopened = readDxf(decodeDxfBytes(new TextEncoder().encode(written)).text);
    expect((reopened.entities[0] as MTextEntity).text).toBe(text); expect(written).not.toContain('\ufffd');
  });
});
